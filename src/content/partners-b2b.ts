function priceLabel(pkg: PackageKey): string {
  const p = PACKAGES[pkg];
  if (pkg === "contour") return `от ${fmtMln(p.price as number)} / год`;
  if (pkg === "project") return "20–150 млн сум";
  return `${fmtMln(p.price as number)} / ${p.period}`;
}

