import type { ReactNode } from "react";

/**
 * Подсветка времени в готовом тексте.
 *
 * Оператор попросил, чтобы время на сайте было видно сразу и везде. Разметить
 * его руками нельзя: часы стоят в десятках строк на трёх языках, половина из
 * них собирается из константы (`Работает ежедневно ${poolPricing.hours}`), и
 * любая новая фраза про время оказалась бы неразмеченной. Поэтому подсветка
 * живёт не в контенте, а в отрисовке: контент остаётся чистым текстом — тем
 * самым, который уходит в разметку для Google и в брифинги ИИ, — а жирным его
 * делает уже страница.
 *
 * Ловит и «10:00–20:00», и одиночные «с 15:00», и «08:00 до 11:00»: у оператора
 * все три формы в ходу.
 */
const TIME = /(\d{1,2}:\d{2}(?:\s*(?:[–—-]|до|dan|to|gacha)\s*\d{1,2}:\d{2})?)/g;

/**
 * Золотой, а не просто bold: серое жирное в примечании остаётся серым, а
 * «очень заметно» — это про цвет. Золото — брендовый акцент кнопок, и оно
 * читается и на светлой бумаге, и на тёмной подложке футера, поэтому цвет
 * один для всех мест.
 */
const MARK = "font-extrabold text-[var(--sun-dark)]";

/** Текст, в котором каждое время обёрнуто в <strong>. Не время — как было. */
export function clock(text: string): ReactNode {
  const parts = text.split(TIME);
  if (parts.length === 1) return text;

  return parts.map((part, i) =>
    // split с одной группой захвата отдаёт совпадения на нечётных позициях.
    i % 2 === 1 ? (
      <strong key={i} className={MARK}>
        {part}
      </strong>
    ) : (
      part
    ),
  );
}

/** Готовый <span> — для мест, где нужен один узел, а не массив. */
export function Clock({ text, className }: { text: string; className?: string }) {
  return <span className={className}>{clock(text)}</span>;
}
